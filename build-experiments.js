// Rebuild browser data and recorded results from the two bundled, original corpora.
const fs = require('node:fs');
const path = require('node:path');
const core = require('./cipher-core.js');
const read = name => fs.readFileSync(path.join(__dirname, 'data', name), 'utf8');
const training = read('training-english.txt');
const testing = read('test-english.txt');
const model = core.train(training);
const testLetters = core.letters(testing);
const results = core.experiment(testLetters, model);
const data = {model, testLetters, results};
fs.writeFileSync(path.join(__dirname, 'experiment-data.js'),
  '// Generated by node build-experiments.js; original corpora are in data/.\nwindow.ExperimentData = ' + JSON.stringify(data) + ';\n');
fs.writeFileSync(path.join(__dirname, 'data', 'results.json'), JSON.stringify({
  seed: 20261022, trainingLetters: model.size, testLetters: testLetters.length,
  trialsPerLength: 100, sampling: 'Contiguous windows, with replacement; all methods share each window and key.', results
}, null, 2) + '\n');
console.log(JSON.stringify({trainingLetters: model.size, testLetters: testLetters.length, results}, null, 2));
